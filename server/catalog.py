def public_catalog():
    courses = deepcopy(COURSES)
    for course in courses:
        course["pilot"] = True
        course["format"] = "텍스트 클래스"
        course["lessons"] = [
            {key: item[key] for key in ("id", "title", "duration", "free")}
            for item in LESSONS[course["id"]]
        ]
    return {"courses": courses, "coaches": deepcopy(COACHES)}


def find_course(course_id):
    return next((course for course in COURSES if course["id"] == course_id), None)


def find_coach(coach_id):
    return next((coach for coach in COACHES if coach["id"] == coach_id), None)


def find_lesson(course_id, lesson_id):
    return next((item for item in LESSONS.get(course_id, []) if item["id"] == lesson_id), None)
